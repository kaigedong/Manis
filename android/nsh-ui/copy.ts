export async function setLanguage(next: Lang): Promise<void> {
  lang.set(next);
  try {
    await Storage.setItem("language", next);
  } catch {
    // The switch still applies to this run.
  }
}

if (typeof Storage !== "undefined") {
  void loadLanguage();
}
